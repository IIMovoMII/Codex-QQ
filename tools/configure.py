"""First-use configuration only. Refuses to replace an existing installation."""
from __future__ import annotations

import argparse
import getpass
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src/codex_desktop_weixin'))
from runtime_io import atomic_write_json, default_data_dir

PROJECT = 'codex-qq'
BLOCKED_COMMANDS = ('new list switch name current status usage history allow model reasoning mode lang quiet '
                    'provider memory cron timer heartbeat compress stop cancel help start version commands skills '
                    'config doctor upgrade restart alias delete bind search shell diff show dir tts workspace '
                    'whoami web ps').split()


def atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.' + path.name, suffix='.tmp', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def config_text(root: Path, data: Path, app_id: str, secret: str, openid: str = '', *, sandbox=False) -> str:
    def q(value):
        return json.dumps(str(value), ensure_ascii=False)
    script = root / ('src/codex_desktop_weixin/qq_desktop_bridge.py' if openid else 'tools/pairing_agent.py')
    command = json.dumps([sys.executable, '-X', 'utf8', str(script)], ensure_ascii=False)
    text = f'''# Generated by Codex-QQ. Contains a secret; keep outside the repository.
language = "zh"
data_dir = {q(data)}
attachment_send = "off"

[log]
level = "info"
[display]
mode = "quiet"
thinking_messages = false
tool_messages = false

[[projects]]
name = "{PROJECT}"
reset_on_idle_mins = 0
filter_external_sessions = true
admin_from = "__no_remote_admin__"
disabled_commands = {json.dumps(BLOCKED_COMMANDS)}

[projects.agent]
type = "acp"
[projects.agent.options]
cmd = {command}
work_dir = {q(root)}
mode = "suggest"
display_name = "Codex-QQ"

[[projects.platforms]]
type = "qqbot"
[projects.platforms.options]
app_id = {q(app_id)}
app_secret = {q(secret)}
sandbox = {str(sandbox).lower()}
allow_from = {q(openid or '*')}
markdown_support = false
'''
    tomllib.loads(text)
    return text


def prepare(root: Path, runtime: Path, cc_data: Path, app_id: str, secret: str, sandbox: bool) -> Path:
    # Do not touch the running user's existing settings, even when --bind was
    # mistakenly used against a directory from an older, manually set-up copy.
    config = runtime / 'cc-connect.toml'
    if any((runtime / name).exists() for name in ('settings.json', 'setup-pending.json', 'cc-connect.toml')):
        raise ValueError('此处已有配置，拒绝覆盖。已有用户更新源码即可，不要重复首次配置。')
    if cc_data.exists() and any(cc_data.iterdir()):
        raise ValueError('CC Connect 数据目录已有内容，拒绝接管或覆盖。请先检查现有安装。')
    if not re.fullmatch(r'\d{5,30}', app_id) or not secret.strip() or '\n' in secret or '\r' in secret:
        raise ValueError('AppID 或 AppSecret 格式不正确。')
    if len(str(cc_data / 'run/api.sock').encode('utf-8')) >= 104:
        raise ValueError('QQ 数据路径过长，请用 --cc-data-dir 指定更短的当前用户私有目录。')
    text = config_text(root, cc_data, app_id, secret, sandbox=sandbox)
    atomic_write_text(config, text)
    atomic_write_json(runtime / 'setup-pending.json', {'version': 1, 'root': str(root.resolve()),
        'config_sha256': hashlib.sha256(config.read_bytes()).hexdigest(), 'cc_data': str(cc_data.resolve())})
    return config


def bind(root: Path, runtime: Path, openid: str) -> None:
    if not re.fullmatch(r'[A-Za-z0-9_-]{8,128}', openid) or openid.isdecimal():
        raise ValueError('请填机器人返回的 OpenID，不是普通 QQ 号。')
    if (runtime / 'settings.json').exists():
        raise ValueError('已有正式配置，拒绝覆盖。')
    pending = runtime / 'setup-pending.json'
    state = json.loads(pending.read_text(encoding='utf-8'))
    config = runtime / 'cc-connect.toml'
    if (state.get('version') != 1 or state.get('root') != str(root.resolve())
            or state.get('config_sha256') != hashlib.sha256(config.read_bytes()).hexdigest()):
        raise ValueError('首次配置文件已变化，拒绝自动替换。')
    parsed = tomllib.loads(config.read_text(encoding='utf-8'))
    opts = parsed['projects'][0]['platforms'][0]['options']
    executable = root / 'vendor/cc-connect/v1.5.0-desktop-control/bin/cc-connect-desktop-control.exe'
    if not executable.is_file():
        raise ValueError('请先按安装文档构建 CC Connect 适配版。')
    # User stops the foreground pairing gateway before this step. The native
    # app later owns the production process; no forced kills during setup.
    cc_data = Path(state['cc_data'])
    old = config.read_text(encoding='utf-8')
    try:
        atomic_write_text(config, config_text(root, cc_data, opts['app_id'], opts['app_secret'], openid,
                                             sandbox=opts.get('sandbox', False)))
        atomic_write_json(runtime / 'settings.json', {'mode': 'cc-connect', 'executable': str(executable),
            'project': PROJECT, 'session': 'qqbot:' + openid, 'data_dir': str(cc_data),
            'config_path': str(config), 'timeout_seconds': 15})
    except Exception:
        atomic_write_text(config, old)
        raise
    pending.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description='Codex-QQ 首次配置，不覆盖已有安装；密钥不通过命令行传入')
    parser.add_argument('--bind', action='store_true')
    parser.add_argument('--sandbox', action='store_true', help='使用 QQ 沙箱机器人')
    parser.add_argument('--data-dir', type=Path, default=default_data_dir())
    parser.add_argument('--cc-data-dir', type=Path, default=Path(os.environ.get('LOCALAPPDATA', '.')) / 'CodexCC')
    args = parser.parse_args()
    if os.name != 'nt':
        raise SystemExit('当前版本仅支持 Windows。')
    try:
        if args.bind:
            print('请先在配置网关的窗口按 Ctrl+C 停止它。')
            openid = input('粘贴你在 QQ 私聊中收到的 OpenID：').strip()
            if input('只允许这个 QQ 身份控制电脑，确认请输入 yes：').strip() != 'yes':
                print('已取消，没有写入。')
                return
            bind(ROOT, args.data_dir.resolve(), openid)
            print('绑定已保存。接下来按安装文档启用钩子并启动应用；尚未自动启动或启用自启。')
        else:
            app_id = input('QQ 机器人 AppID：').strip()
            secret = getpass.getpass('QQ 机器人 AppSecret（输入不显示）：')
            config = prepare(ROOT, args.data_dir.resolve(), args.cc_data_dir.resolve(), app_id, secret, args.sandbox)
            print('首次配置文件：' + str(config))
            print('按安装文档用此文件启动配置网关，QQ 私聊发送“绑定”。当前只查询身份，不连接 Codex。')
    except (ValueError, OSError, KeyError) as error:
        # Parser errors can contain the credential line. Print the class rather
        # than an arbitrary exception body if it is not one of our own messages.
        if isinstance(error, tomllib.TOMLDecodeError):
            raise SystemExit('配置格式不正确；请在本机检查，不要上传含密钥的文件。') from None
        raise SystemExit(str(error) if type(error) is ValueError else '配置未完成：' + type(error).__name__) from None


if __name__ == '__main__':
    main()
